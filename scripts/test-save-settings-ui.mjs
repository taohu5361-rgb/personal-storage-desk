import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1500,height:1000}});
const checks=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',e=>{if(e.type()==='error')errors.push(e.text());});
const passed=message=>{checks.push(message);console.log('PASS '+message);};
const settingWrites=()=>page.evaluate(()=>window.uiQA.writes().filter(w=>w.command==='save_settings'));
const saved=()=>page.evaluate(()=>window.uiQA.state().settings);
const wait=()=>page.waitForTimeout(160);
try {
  await page.goto(`${process.env.UI_TEST_BASE_URL||'http://127.0.0.1:1450'}/scripts/verify-ui-system.html#/settings`);
  const interval=page.getByRole('spinbutton',{name:'保存间隔',exact:true});
  const preset=page.getByRole('combobox',{name:'保存间隔预设'});
  const mode=page.getByRole('combobox',{name:'保存方式'});
  await interval.waitFor();
  assert.equal(await interval.inputValue(),'60');
  assert.equal(await preset.inputValue(),'60');
  assert.equal(await mode.inputValue(),'automatic');
  passed('默认60秒，独立设置保存方式、间隔及常用预设');
  let before=(await settingWrites()).length;
  await interval.fill('90');await wait();
  assert.equal((await settingWrites()).length,before);
  await interval.press('Enter');await wait();
  assert.equal((await settingWrites()).length,before+1);
  assert.equal((await saved()).autoSaveInterval,90);
  assert.equal(await preset.inputValue(),'custom');
  passed('自定义90秒只在确认时保存设置，输入中不逐字写入');
  before=(await settingWrites()).length;
  await preset.selectOption('300');await wait();
  assert.equal(await interval.inputValue(),'300');
  assert.equal((await saved()).autoSaveInterval,300);
  assert.equal((await settingWrites()).length,before+1);
  passed('5分钟预设与手填间隔一致，设置单次写入');
  before=(await settingWrites()).length;
  await interval.fill('2');await interval.press('Enter');await wait();
  assert.equal(await interval.inputValue(),'300');
  assert.equal((await settingWrites()).length,before);
  assert.equal((await saved()).autoSaveInterval,300);
  passed('非法间隔保留已确认设置，无无效写入');
  await interval.fill('120');await interval.press('Escape');await wait();
  assert.equal(await interval.inputValue(),'300');
  assert.equal((await settingWrites()).length,before);
  passed('Escape取消输入且不通过blur偷写');
  await mode.selectOption('manual');await wait();
  assert.equal((await saved()).autoSave,false);
  assert.equal((await saved()).autoSaveInterval,300);
  assert.equal(await interval.isDisabled(),true);
  assert.equal(await preset.isDisabled(),true);
  passed('仅手动保存停用间隔控件，同时保留用户间隔');
  await page.evaluate(()=>{location.hash='home';});await page.waitForSelector('.ui-home');
  await page.evaluate(()=>{location.hash='settings';});await mode.waitFor();
  assert.equal(await mode.inputValue(),'manual');
  assert.equal(await interval.inputValue(),'300');
  await mode.selectOption('automatic');await wait();
  assert.equal((await saved()).autoSave,true);
  assert.equal(await interval.isDisabled(),false);
  passed('离开再返回保留manual与自定义设置，可重新启用自动保存');
  await page.evaluate(()=>window.uiQA.fail('save_settings'));
  await preset.selectOption('60');await wait();
  assert.equal((await saved()).autoSaveInterval,300);
  assert.equal(await interval.inputValue(),'300');
  assert.equal(await page.getByRole('button',{name:'重试保存',exact:true}).count(),1);
  await page.evaluate(()=>window.uiQA.fail(''));
  await page.getByRole('button',{name:'重试保存',exact:true}).click();await wait();
  assert.equal((await saved()).autoSaveInterval,60);
  assert.equal(await interval.inputValue(),'60');
  passed('设置写入失败回滚，显式重试保存原目标');
  assert.deepEqual(errors,[]);
  const out='.impeccable/evidence/fixed-save/settings';await mkdir(out,{recursive:true});
  await page.screenshot({path:`${out}/settings.png`});
  await writeFile(`${out}/result.json`,JSON.stringify({checks,errors},null,2));
  console.log(`PASS ${checks.length} save settings scenarios; console clean`);
} finally {await browser.close();}
